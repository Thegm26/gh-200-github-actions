import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument } from 'yaml';
import { courseCopy, courseInstructions, courseOutcomes, courseTasks } from '../learning/course-copy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const normalized = (value) => value.replace(/\r\n/g, '\n');
const read = (file) => normalized(fs.readFileSync(path.join(root, file), 'utf8'));
const clean = (value) => value.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/`([^`]+)`/g, '$1').replace(/\*\*([^*]+)\*\*/g, '$1').replace(/\s+/g, ' ').trim();
const stageFor = (index) => index <= 4 ? 'Foundations' : index <= 8 ? 'Connect jobs' : index <= 11 ? 'Reuse and debug' : 'Secure delivery';
const official = (markdown) => {
  const match = markdown.match(/\[([^\]]+)\]\((https:\/\/(?:docs\.github\.com|learn\.microsoft\.com)[^)]+)\)/);
  return match ? { label: clean(match[1]), url: match[2] } : { label: 'GitHub Actions documentation', url: 'https://docs.github.com/actions' };
};
const explanation = (markdown) => {
  const lead = markdown.split(/^## Do\s*$/m)[0].replace(/^#.*$/m, '').replace(/```[\s\S]*?```/g, '');
  return lead.split(/\n\s*\n/).map(clean).filter(Boolean);
};
const example = (markdown) => (markdown.split(/^## Do\s*$/m)[0].match(/```ya?ml\n([\s\S]*?)```/) || [])[1] || '';
const readableYaml = (source) => {
  const document = parseDocument(normalized(source), { merge: true });
  if (document.errors.length) throw new Error(document.errors[0].message);
  return document.toString({ collectionStyle: 'block' }).replace(/\r\n/g, '\n');
};

export function courseDataSource() {
  const manifest = JSON.parse(read('learning/manifest.json'));
  const lessons = manifest.labs.map((lab, offset) => {
    const index = offset + 1; const exercisePath = `exercises/${lab.id}/README.md`; const markdown = read(exercisePath);
    const copy = courseCopy[lab.id];
    const task = courseTasks[lab.id];
    if (!copy || copy.length !== 3 || !copy[2]?.length || !task || !['goal', 'location', 'keep', 'example'].every((field) => typeof task[field] === 'string')) throw new Error(`Missing browser course copy for ${lab.id}`);
    if (!Array.isArray(courseInstructions[lab.id]) || courseInstructions[lab.id].length < 2 || typeof courseOutcomes[lab.id] !== 'string') throw new Error(`Missing browser instructions for ${lab.id}`);
    return { id: lab.id, index, title: copy[0], stage: stageFor(index), summary: copy[1], explanation: copy[2], instructions: courseInstructions[lab.id], doneWhen: courseOutcomes[lab.id], task: task.goal, editLocation: task.location, keep: task.keep, editExample: task.example || '', example: normalized(example(markdown)), starter: readableYaml(read(`learning/starters/${lab.id}/${lab.file}`)), solution: readableYaml(read(`learning/solutions/${lab.id}/${lab.file}`)), file: lab.file, hint: task.location, success: courseOutcomes[lab.id], source: official(markdown), rules: lab.rules };
  });
  return `// Generated by scripts/build-course.mjs; do not hand-edit.\nexport const lessons = ${JSON.stringify(lessons, null, 2)};\n`;
}
export const courseDataPath = path.join(root, 'learning', 'course-data.mjs');
export function writeCourseData() { fs.writeFileSync(courseDataPath, courseDataSource()); }
